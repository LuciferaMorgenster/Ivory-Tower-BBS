/**
 * Returns translated string for given key and language, falling back to English.
 */
export function t(key: string, lang: SupportedLanguage = 'en', ...args: any[]): string {
  const langDict = TRANSLATIONS[lang] || TRANSLATIONS.en;
  let text = langDict[key] || TRANSLATIONS.en[key] || key;

  if (args.length > 0) {
    args.forEach(arg => {
      text = text.replace('%s', String(arg));
    });
  }

  return text;
}
